package com.cakedelight.catalog.service;

import com.cakedelight.catalog.exception.ResourceNotFoundException;
import com.cakedelight.catalog.model.Cake;
import com.cakedelight.catalog.repository.CakeRepository;
import com.cakedelight.catalog.repository.CakeSpecifications;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.util.List;

@Service
@Transactional(readOnly = true)
public class CakeService {

    private final CakeRepository cakeRepository;

    public CakeService(CakeRepository cakeRepository) {
        this.cakeRepository = cakeRepository;
    }

    public List<Cake> search(String name, String category, BigDecimal minPrice, BigDecimal maxPrice) {
        validatePriceRange(minPrice, maxPrice);
        return cakeRepository.findAll(
                CakeSpecifications.matching(name, category, minPrice, maxPrice), Sort.by("id"));
    }

    public Cake getCakeById(Long id) {
        return cakeRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Cake with id " + id + " was not found"));
    }

    public List<Cake> filterByName(String name) {
        return cakeRepository.findByNameContainingIgnoreCaseOrderByIdAsc(name.trim());
    }

    public List<Cake> filterByCategory(String category) {
        return cakeRepository.findByCategoryIgnoreCaseOrderByIdAsc(category.trim());
    }

    public List<Cake> filterByPrice(BigDecimal minPrice, BigDecimal maxPrice) {
        validatePriceRange(minPrice, maxPrice);
        return cakeRepository.findByPriceBetweenOrderByIdAsc(minPrice, maxPrice);
    }

    @Transactional
    public Cake addCake(Cake cake) {
        // The id is always generated by the database. Ignoring a client-supplied
        // id prevents a create request from overwriting an existing cake.
        cake.setId(null);
        return cakeRepository.save(cake);
    }

    private static void validatePriceRange(BigDecimal minPrice, BigDecimal maxPrice) {
        if (minPrice != null && minPrice.signum() < 0) {
            throw new IllegalArgumentException("min price must be zero or positive");
        }
        if (minPrice != null && maxPrice != null && minPrice.compareTo(maxPrice) > 0) {
            throw new IllegalArgumentException("min price must not be greater than max price");
        }
    }
}
